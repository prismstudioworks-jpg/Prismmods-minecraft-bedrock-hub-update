const STORAGE_KEY_LANG = 'prismmods_app_language';

export function getStoredLanguage(): string {
  try {
    return localStorage.getItem(STORAGE_KEY_LANG) || 'en';
  } catch {
    return 'en';
  }
}

export function setStoredLanguage(code: string): void {
  try {
    localStorage.setItem(STORAGE_KEY_LANG, code);
  } catch {}
}

export function getTranslation(key: keyof TranslationDictionary, langCode?: string): string {
  const current = langCode || getStoredLanguage();
  const dict = TRANSLATIONS[current] || TRANSLATIONS['en'];
  return dict[key] || TRANSLATIONS['en'][key] || String(key);
}
